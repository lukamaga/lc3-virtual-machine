        .ORIG x3000

        ; Загрузить два числа, сложить их
        LD    R1, NUM1       ; R1 <- M[NUM1]
        LD    R2, NUM2       ; R2 <- M[NUM2]
        ADD   R3, R1, R2     ; R3 = R1 + R2

        ; Печатаем "Sum: "
        LEA   R0, MSG
        PUTS

        ; Вызываем подпрограмму для вывода R3 в виде десятичного числа
        JSR   DECOUT

        TRAP  x25            ; Остановка (HALT)


;-----------------------------------------------------------
; Подпрограмма DECOUT: выводит (в R3) неотрицательное число
; в десятичном формате, максимум 5 знаков (0..32767).
; Использует регистры R4..R7 как рабочие.
;-----------------------------------------------------------
DECOUT
        ; Если R3 == 0, сразу печатаем '0' и выходим
        NOT   R7, R3
        ADD   R7, R7, #1     ; R7 = -R3
        BRz   PRINT_ZERO     ; Если R3=0, печатаем '0' и выходим

        ; R5 будет говорить, что мы начали печатать (0 - ещё нет)
        AND   R5, R5, #0

        ; Обрабатываем последовательно разряды 10000, 1000, 100, 10, 1
        LD    R6, PLACE_10000
        JSR   PRINT_DIGIT

        LD    R6, PLACE_1000
        JSR   PRINT_DIGIT

        LD    R6, PLACE_100
        JSR   PRINT_DIGIT

        LD    R6, PLACE_10
        JSR   PRINT_DIGIT

        LD    R6, PLACE_1
        JSR   PRINT_DIGIT

        ; Если все цифры были 0 => напечатаем '0'
        ADD   R7, R5, #-1
        BRnp  DONE_DECOUT

PRINT_ZERO
        LD    R0, ASCII0
        OUT
DONE_DECOUT:
        RET

;-----------------------------------------------------------
; Подпрограмма PRINT_DIGIT:
; - R6 содержит "разряд" (10, 100, 1000 и т.п.).
; - Цикл вычитает R6 из R3, пока R3 >= R6, чтобы найти "цифру".
; - Печатает найденную цифру, если она не 0 или если уже начали печатать.
;-----------------------------------------------------------
PRINT_DIGIT
        AND   R4, R4, #0     ; R4 = 0 (будущая цифра)
LOOP_SUB:
        NOT   R7, R6
        ADD   R7, R7, #1     ; R7 = -R6
        ADD   R7, R7, R3     ; R7 = R3 - R6
        BRn   DONE_SUB       ; если (R3-R6)<0, выходим
        ADD   R3, R3, R7     ; R3 = R3 - R6
        ADD   R4, R4, #1     ; digit++
        BR    LOOP_SUB
DONE_SUB:
        ; Если цифра > 0, печатаем её
        ; Или, если цифра = 0, но уже начали печатать (R5>0), тоже печатаем
        BRz   CHECK_ZERO     ; если digit=0 => см. ниже
        ADD   R5, R5, #1     ; отметка, что начали печатать
        LD    R1, ASCII0
        ADD   R0, R4, R1
        OUT
        BR    SKIP_PRINT

CHECK_ZERO:
        ; digit=0 - печатаем только если уже начали вывод
        ADD   R7, R5, #0
        BRz   SKIP_PRINT
        LD    R1, ASCII0
        ADD   R0, R4, R1
        OUT

SKIP_PRINT:
        RET


;-----------------------------------------------------------
; Данные
; Измените NUM1/NUM2 на любые 16-битные числа (0..32767).
;-----------------------------------------------------------
NUM1        .FILL   1234
NUM2        .FILL   567

MSG         .STRINGZ "Sum: "

ASCII0      .FILL   x0030      ; '0'
PLACE_10000 .FILL   10000
PLACE_1000  .FILL   1000
PLACE_100   .FILL   100
PLACE_10    .FILL   10
PLACE_1     .FILL   1

        .END
